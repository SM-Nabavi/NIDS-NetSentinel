# CLI
# ============================================================

if __name__ == "__main__":

    action = (
        sys.argv[1]
        if len(sys.argv) > 1
        else "status"
    )


    # --------------------------------------------------------
    # STATUS
    # --------------------------------------------------------

    if action == "status":

        print(
            json.dumps(
                get_status(),
                ensure_ascii=False
            )
        )


    # --------------------------------------------------------
    # START
    # --------------------------------------------------------

    elif action == "start":

        if len(sys.argv) < 3:

            print(
                json.dumps(
                    {
                        "status": "error",
                        "error": (
                            "Capture device is required. "
                            "Example: python "
                            "soc_pipeline_mgr.py start "
                            "\"\\\\Device\\\\NPF_{GUID}\""
                        )
                    },
                    ensure_ascii=False
                )
            )

            sys.exit(1)


        interface = sys.argv[2]

        print(
            json.dumps(
                start_pipeline(interface),
                ensure_ascii=False
            )
        )


    # --------------------------------------------------------
    # STOP
    # --------------------------------------------------------

    elif action == "stop":

        print(
            json.dumps(
                stop_pipeline(),
                ensure_ascii=False
            )
        )


    # --------------------------------------------------------
    # LOGS
    # --------------------------------------------------------

    elif action == "logs":

        count = (
            int(sys.argv[2])
            if len(sys.argv) > 2
            else 50
        )

        print(
            json.dumps(
                get_logs(count),
                ensure_ascii=False
            )
        )


    # --------------------------------------------------------
    # COMBINED LOGS
    # --------------------------------------------------------

    elif action == "combined-logs":

        count = (
            int(sys.argv[2])
            if len(sys.argv) > 2
            else 100
        )

        print(
            json.dumps(
                get_combined_logs(count),
                ensure_ascii=False
            )
        )


    # --------------------------------------------------------
    # UNKNOWN COMMAND
    # --------------------------------------------------------

    else:

        print(
            json.dumps(
                {
                    "status": "error",
                    "error": f"Unknown action: {action}"
                },
                ensure_ascii=False
            )
        )

        sys.exit(1)